#include <iostream>

using namespace std;

int main()
{
    // Begin8 Дано два числа a і b. Знайти їх середнє арифметичне: (a + b) / 2.
   
    cout << " Задача Begin8 " << endl;

    // Оголошення змінних дійсного типу
    double a8, b8, avg8;

    // Введення вхідних даних
    cout << "Введіть перше число (a): ";
    cin >> a8;
    cout << "Введіть друге число (b): ";
    cin >> b8;

    // Обчислення середнього арифметичного
    avg8 = (a8 + b8) / 2.0;

    // Виведення результату
    cout << "Середнє арифметичне (Begin8): " << avg8 << endl << endl;


    // Begin34 Дано три числа. Знайти їх середнє арифметичне: (a + b + c)/3.
   
    cout << " Задача Begin34 " << endl;

    // Оголошення змінних дійсного типу
    double a34, b34, c34, avg34;

    // Введення вхідних даних
    cout << "Введіть перше число (a): ";
    cin >> a34;
    cout << "Введіть друге число (b): ";
    cin >> b34;
    cout << "Введіть третє число (c): ";
    cin >> c34;

    // Обчислення середнього арифметичного трьох чисел
    avg34 = (a34 + b34 + c34) / 3.0;

    // Виведення результату
    cout << "Середнє арифметичне (Begin34): " << avg34 << endl << endl;

// Begin35 Дано три числа. Знайти суму їх квадратів: a2 + b2 + c2.
    
    cout << " Задача Begin35 " << endl;

    // Оголошення змінних дійсного типу
    double a35, b35, c35, sum_sq35;

    // Введення вхідних даних
    cout << "Введіть перше число (a): ";
    cin >> a35;
    cout << "Введіть друге число (b): ";
    cin >> b35;
    cout << "Введіть третє число (c): ";
    cin >> c35;

    // Обчислення суми квадратів (використовуючи лише операції + та *)
    sum_sq35 = a35 * a35 + b35 * b35 + c35 * c35;

    // Виведення результату
    cout << "Сума квадратів (Begin35): " << sum_sq35 << endl;

    return 0;
}
